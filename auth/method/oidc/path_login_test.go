func TestAuthURL(t *testing.T) {
	e := newEnv(t)
	e.mustConfigure(nil)
	binding, _ := secret()
	resp := e.call(e.b, "auth_url", map[string]any{"redirect_uri": testRedirect, "login_binding": binding})
	require.NoError(t, resp.Err)
	u, err := url.Parse(resp.Data["auth_url"].(string))
	require.NoError(t, err)
	q := u.Query()
	assert.Equal(t, e.tp.Addr()+"/authorize", u.Scheme+"://"+u.Host+u.Path)
	assert.Equal(t, "S256", q.Get("code_challenge_method"))
	assert.NotEmpty(t, q.Get("code_challenge"))
	assert.NotEmpty(t, q.Get("nonce"))
	assert.Equal(t, resp.Data["state"], q.Get("state"))
	assert.Equal(t, testRedirect, q.Get("redirect_uri"))
	assert.Equal(t, "openid profile", q.Get("scope"))
	assert.Empty(t, q.Get("code_verifier"), "the verifier never leaves the sealed state")

	for name, data := range map[string]map[string]any{
		"no binding":           {"redirect_uri": testRedirect},
		"short binding":        {"redirect_uri": testRedirect, "login_binding": "abc"},
		"redirect not allowed": {"redirect_uri": "http://evil.example/cb", "login_binding": binding},
		"no redirect":          {"login_binding": binding},
	} {
		resp := e.call(e.b, "auth_url", data)
		assert.Equal(t, http.StatusBadRequest, resp.StatusCode, name)
	}
}

func TestLogin_PrivateKeyJWT(t *testing.T) {
	e := newEnv(t)
	_, keyPEM, _ := rsaKey(t)
	e.mustConfigure(map[string]any{"client_auth": "private_key_jwt", "client_secret": nil, "private_key": keyPEM})

	var gotTokenURL string
	e.b.newAssertion = func(_ *oidcConfig, tokenURL string) (string, error) {
		gotTokenURL = tokenURL
		return "assertion-jwt", nil
	}
	e.tp.SetClientAssertionJWT("assertion-jwt")
	resp := e.login(personClaims())
	require.NoError(t, resp.Err)
	assert.Equal(t, e.tp.Addr()+"/token", gotTokenURL, "the assertion's audience is the token endpoint")

	e.tp.SetClientAssertionJWT("another-assertion")
	resp = e.login(personClaims())
	assert.Equal(t, http.StatusUnauthorized, resp.StatusCode, "the provider refuses an assertion it does not expect")
}

// Each client_auth sends exactly one client authentication, in the form the
// method prescribes, and the PKCE verifier.
func TestExchangeCode_OneClientAuth(t *testing.T) {
	type seen struct {
		basicUser, basicPass string
		hasBasic             bool
		form                 url.Values
	}
	var got seen
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		require.NoError(t, r.ParseForm())
		u, p, ok := r.BasicAuth()
		got = seen{basicUser: u, basicPass: p, hasBasic: ok, form: r.PostForm}
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(`{"access_token":"at","token_type":"Bearer","id_token":"x.y.z"}`))
	}))
	t.Cleanup(srv.Close)

	ctx := context.Background()
	for _, tc := range []struct {
		cfg       *oidcConfig
		assertion string
		check     func()
	}{
		{&oidcConfig{ClientID: "c", ClientAuth: clientAuthSecret, ClientSecret: "s"}, "", func() {
			assert.True(t, got.hasBasic)
			assert.Equal(t, "c", got.basicUser)
			assert.Equal(t, "s", got.basicPass)
			assert.Empty(t, got.form.Get("client_secret"))
			assert.Empty(t, got.form.Get("client_assertion"))
		}},
		{&oidcConfig{ClientID: "c", ClientAuth: clientAuthNone}, "", func() {
			assert.False(t, got.hasBasic, "no Basic header with an empty secret")
			assert.Equal(t, "c", got.form.Get("client_id"))
			assert.False(t, got.form.Has("client_secret"))
		}},
		{&oidcConfig{ClientID: "c", ClientAuth: clientAuthKeyJWT}, "signed", func() {
			assert.False(t, got.hasBasic, "the assertion is the only client authentication")
			assert.Equal(t, "signed", got.form.Get("client_assertion"))
			assert.Equal(t, clientAssertionType, got.form.Get("client_assertion_type"))
			assert.False(t, got.form.Has("client_secret"))
		}},
	} {
		tok, err := exchangeCode(ctx, tc.cfg, srv.URL, testRedirect, "the-code", "the-verifier", tc.assertion)
		require.NoError(t, err, tc.cfg.ClientAuth)
		assert.Equal(t, "x.y.z", tok.Extra("id_token"))
		assert.Equal(t, "the-code", got.form.Get("code"))
		assert.Equal(t, "the-verifier", got.form.Get("code_verifier"))
		assert.Equal(t, "authorization_code", got.form.Get("grant_type"))
		assert.Equal(t, testRedirect, got.form.Get("redirect_uri"))
		tc.check()
	}
}

func TestNewClientAssertion(t *testing.T) {
	key, keyPEM, certPEM := rsaKey(t)
	cfg := &oidcConfig{ClientID: testClientID, ClientAuth: clientAuthKeyJWT, PrivateKey: keyPEM,
		ClientCertificate: certPEM, ClientAssertionKID: "kid-1"}
	require.NoError(t, cfg.checkClientAuth())
	raw, err := newClientAssertion(cfg, "https://idp.example/token")
	require.NoError(t, err)

	tok, err := jwt.ParseSigned(raw, []jose.SignatureAlgorithm{jose.RS256})
	require.NoError(t, err)
	assert.Equal(t, "kid-1", tok.Headers[0].KeyID)
	assert.Equal(t, cfg.x5tS256, tok.Headers[0].ExtraHeaders["x5t#S256"])
	var claims jwt.Claims
	require.NoError(t, tok.Claims(&key.PublicKey, &claims))
	assert.Equal(t, testClientID, claims.Issuer)
	assert.Equal(t, testClientID, claims.Subject)
	assert.Equal(t, jwt.Audience{"https://idp.example/token"}, claims.Audience)
	assert.NotEmpty(t, claims.ID)
	assert.True(t, claims.Expiry.Time().After(time.Now()))
}

