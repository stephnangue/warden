func TestLogin_ClientSecret(t *testing.T) {
	e := newEnv(t)
	e.mustConfigure(nil)

	resp := e.login(personClaims())
	require.NoError(t, resp.Err)
	auth := resp.Auth
	require.NotNil(t, auth)
	assert.Equal(t, logical.TokenTypeTicket, auth.TokenType)
	assert.Equal(t, time.Hour, auth.TokenTTL)
	assert.Equal(t, "0583-oid", auth.PrincipalID)
	assert.Empty(t, auth.ClientToken, "a ticket is generated by core, from the admission")

	adm := auth.Admission
	require.NotNil(t, adm)
	assert.Empty(t, adm.MountPath, "core names the mount")
	assert.Empty(t, adm.MountAccessor)
	assert.Empty(t, adm.AliasName, "core derives the alias")
	assert.Equal(t, "0583-oid", adm.PrincipalID)
	assert.Same(t, e.b.mountFacts, adm.Mount)

	n := e.b.mountFacts.Load()
	assert.Equal(t, logical.EntityKindHuman, n.Kind)
	assert.Equal(t, "0583-oid", adm.DeriveAlias(n))
	assert.Equal(t, []string{"Warden.Operator"}, lookup(adm, n, "roles"))
	assert.Equal(t, []string{"CM"}, lookup(adm, n, "country"), "a JSON-pointer source")
	assert.Equal(t, []string{"3"}, lookup(adm, n, "level"), "a number keeps its type")
	assert.Equal(t, []string{"true"}, lookup(adm, n, "admin"), "a boolean keeps its type")
	assert.Equal(t, []string{testClientID}, lookup(adm, n, "aud"))
	assert.Equal(t, []string{e.tp.Addr()}, lookup(adm, n, "iss"))

	// Only what the mount reads is kept: the unmapped email is gone.
	raw, err := adm.Facts.(*selector.Claims).EncodeJSON()
	require.NoError(t, err)
	assert.NotContains(t, string(raw), "ada@example.com")
	assert.NotContains(t, string(raw), "nonce")
}

